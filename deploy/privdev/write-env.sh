#!/usr/bin/env bash
# Write deploy/privdev/<instance>/.env for one AnnotAISE instance.
#
#   deploy/privdev/write-env.sh <annotaise-test|annotaise-study> <public-url> <gateway-port> \
#       [--mail-user ADDRESS] [--mail-from "Name <ADDRESS>"]
#
# Everything host-specific comes from the arguments or the environment:
#   ANNOTAISE_ENV_DIR      output directory (default: <this dir>/<instance>)
#   ANNOTAISE_SECRET_STORE optional directory with one file per secret
#                          (annotaise-db-password, annotaise-django-secret,
#                          annotaise-superuser-password, annotaise-export-password)
#   EMAIL_HOST_USER, DEFAULT_FROM_EMAIL   defaults for --mail-user / --mail-from
#
# A secret is taken from the store when the file exists, else kept from an
# existing .env (so a rerun never rotates the database password), else
# generated randomly. The file is created mode 0600 and is git-ignored. No
# secret value is printed. EMAIL_HOST_PASSWORD is always left empty: the
# operator types the SMTP app password into the .env afterwards.
set -euo pipefail
umask 077

usage="usage: write-env.sh <annotaise-test|annotaise-study> <public-url> <gateway-port> [--mail-user ADDRESS] [--mail-from FROM]"
instance="${1:?$usage}"
public_url="${2:?$usage}"
gateway_port="${3:?$usage}"
shift 3
mail_user="${EMAIL_HOST_USER:-}"
mail_from="${DEFAULT_FROM_EMAIL:-}"
while [ "$#" -gt 0 ]; do
  case "$1" in
    --mail-user) [ "$#" -ge 2 ] || { echo "$usage" >&2; exit 2; }; mail_user="$2"; shift 2 ;;
    --mail-from) [ "$#" -ge 2 ] || { echo "$usage" >&2; exit 2; }; mail_from="$2"; shift 2 ;;
    *) echo "$usage" >&2; exit 2 ;;
  esac
done

# hide_admin: the public study gateway answers 404 for /backend/admin/, the API
# docs/schema and /backend/api/auth/register/ (compose.override.yaml).
case "$instance" in
  annotaise-test) hide_admin=0 ;;
  annotaise-study) hide_admin=1 ;;
  *) echo "unknown instance: $instance" >&2; exit 2 ;;
esac

here="$(cd "$(dirname "$0")" && pwd)"
out_dir="${ANNOTAISE_ENV_DIR:-$here/$instance}"
out="$out_dir/.env"
store="${ANNOTAISE_SECRET_STORE:-}"

public_url="${public_url%/}"
origin="$(printf '%s' "$public_url" | sed -E 's#^(https?://[^/]+).*#\1#')"
host="$(printf '%s' "$origin" | sed -E 's#^https?://([^:/]+).*#\1#')"
base_path="${public_url#"$origin"}"
[ -n "$base_path" ] || { echo "public URL must include the mount path" >&2; exit 2; }

# existing <key> from a previous .env (empty if none)
old() { [ -f "$out" ] && sed -n "s/^$1=//p" "$out" | head -n1 || true; }
# secret <store file> <env key>
secret() {
  local v=""
  if [ -n "$store" ] && [ -f "$store/$1" ]; then v="$(tr -d '\n' < "$store/$1")"; fi
  [ -n "$v" ] || v="$(old "$2")"
  [ -n "$v" ] || v="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  printf '%s' "$v"
}
# keep mail settings from the previous .env unless given again
[ -n "$mail_user" ] || mail_user="$(old EMAIL_HOST_USER)"
[ -n "$mail_from" ] || mail_from="$(old DEFAULT_FROM_EMAIL)"

mkdir -p "$out_dir"
tmp="$(mktemp "$out_dir/.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by write-env.sh - do not commit."
  echo "DEBUG=0"
  echo "GATEWAY_PORT=$gateway_port"
  echo "GATEWAY_HIDE_ADMIN=$hide_admin"
  echo "DJANGO_DB_NAME=annotaise"
  echo "DJANGO_DB_USER=annotaise"
  echo "DJANGO_DB_PASS=$(secret annotaise-db-password DJANGO_DB_PASS)"
  echo "DJANGO_SECRET_KEY=$(secret annotaise-django-secret DJANGO_SECRET_KEY)"
  echo "DJANGO_SUPERUSER_USER=admin"
  echo "DJANGO_SUPERUSER_EMAIL=admin@annotaise.invalid"
  echo "DJANGO_SUPERUSER_PASSWORD=$(secret annotaise-superuser-password DJANGO_SUPERUSER_PASSWORD)"
  echo "ANNOTAISE_EXPORT_PASSWORD=$(secret annotaise-export-password ANNOTAISE_EXPORT_PASSWORD)"
  echo "DJANGO_ALLOWED_HOSTS=$host,localhost,127.0.0.1"
  echo "DJANGO_CSRF_TRUSTED_ORIGINS=$origin"
  echo "DJANGO_CORS_ALLOWED_ORIGINS=$origin"
  echo "DJANGO_FORCE_SCRIPT_NAME=$base_path/backend"
  echo "FRONTEND_URL=$public_url"
  echo "NEXT_PUBLIC_BASE_PATH=$base_path"
  echo "NEXT_PUBLIC_API_BASE_URL=$public_url/backend"
  echo "# Invitation e-mail (Gmail SMTP)."
  echo "# OPERATOR: set EMAIL_HOST_PASSWORD below to the account's app password by"
  echo "# hand, then restart the api container. It is never written by this script."
  echo "EMAIL_HOST=smtp.gmail.com"
  echo "EMAIL_PORT=587"
  echo "EMAIL_USE_TLS=True"
  echo "EMAIL_HOST_USER=$mail_user"
  echo "EMAIL_HOST_PASSWORD="
  echo "DEFAULT_FROM_EMAIL=$mail_from"
} > "$tmp"
chmod 0600 "$tmp"
mv -f "$tmp" "$out"
trap - EXIT
echo "wrote $out (mode 0600)"
