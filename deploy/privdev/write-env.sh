#!/usr/bin/env bash
# Write deploy/privdev/<instance>/.env from the AgentBox secret store.
#
#   sudo deploy/privdev/write-env.sh annotaise-test https://HOST:PORT/annotaise-test 8471
#
# Must run as root (the store is root-only). The file is created mode 0600,
# owned by the invoking user, and is git-ignored (".env"). No secret value is
# printed. Secrets live in /etc/agentbox/secrets/annotaise/<test|study>/.
set -euo pipefail
umask 077

instance="${1:?usage: write-env.sh <annotaise-test|annotaise-study> <public-url> <gateway-port>}"
public_url="${2:?public URL, e.g. https://host.ts.net:9446/annotaise-test}"
gateway_port="${3:?loopback gateway port}"

case "$instance" in
  annotaise-test) area=test ;;
  annotaise-study) area=study ;;
  *) echo "unknown instance: $instance" >&2; exit 2 ;;
esac
[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 2; }

store="/etc/agentbox/secrets/annotaise/$area"
here="$(cd "$(dirname "$0")" && pwd)"
out_dir="$here/$instance"
out="$out_dir/.env"
owner="${SUDO_USER:-root}"

public_url="${public_url%/}"
origin="$(printf '%s' "$public_url" | sed -E 's#^(https?://[^/]+).*#\1#')"
host="$(printf '%s' "$origin" | sed -E 's#^https?://([^:/]+).*#\1#')"
base_path="${public_url#"$origin"}"
[ -n "$base_path" ] || { echo "public URL must include the mount path" >&2; exit 2; }

secret() { tr -d '\n' < "$store/$1"; }

install -d -m 0755 -o "$owner" -g "$owner" "$out_dir"
tmp="$(mktemp "$out_dir/.env.XXXXXX")"
{
  echo "# Generated by write-env.sh from $store - do not commit."
  echo "DEBUG=0"
  echo "GATEWAY_PORT=$gateway_port"
  echo "DJANGO_DB_NAME=annotaise"
  echo "DJANGO_DB_USER=annotaise"
  echo "DJANGO_DB_PASS=$(secret annotaise-db-password)"
  echo "DJANGO_SECRET_KEY=$(secret annotaise-django-secret)"
  echo "DJANGO_SUPERUSER_USER=admin"
  echo "DJANGO_SUPERUSER_EMAIL=admin@annotaise.invalid"
  echo "DJANGO_SUPERUSER_PASSWORD=$(secret annotaise-superuser-password)"
  echo "ANNOTAISE_EXPORT_PASSWORD=$(secret annotaise-export-password)"
  echo "DJANGO_ALLOWED_HOSTS=$host,localhost,127.0.0.1"
  echo "DJANGO_CSRF_TRUSTED_ORIGINS=$origin"
  echo "DJANGO_CORS_ALLOWED_ORIGINS=$origin"
  echo "DJANGO_FORCE_SCRIPT_NAME=$base_path/backend"
  echo "FRONTEND_URL=$public_url"
  echo "NEXT_PUBLIC_BASE_PATH=$base_path"
  echo "NEXT_PUBLIC_API_BASE_URL=$public_url/backend"
  echo "EMAIL_HOST="
  echo "EMAIL_PORT=587"
  echo "EMAIL_HOST_USER="
  echo "EMAIL_HOST_PASSWORD="
  echo "DEFAULT_FROM_EMAIL="
} > "$tmp"
chown "$owner:$owner" "$tmp"
chmod 0600 "$tmp"
mv -f "$tmp" "$out"
echo "wrote $out (mode 0600, owner $owner)"
